"""
Prompt 构建工具模块
------------------
根据 Agent 配置信息动态拼接生成 System Prompt。
将 Agent 的人设（名称、角色、关注领域、输出风格）和
决策模式整合为结构化的指令，要求大模型按固定格式输出。
"""

# ============================================================================
# 六维评分维度定义（与 PRD 一致）
# ============================================================================

# 评分维度对应的 JSON 字段名及其中文说明
SCORING_DIMENSIONS = {
    "benefit": "收益潜力 - 该方案可能带来的正面收益有多大（1=收益很低，10=收益极高）",
    "cost": "成本可控性 - 所需投入（资金、时间、人力）是否可控（1=成本极高难控，10=成本极低易控）",
    "risk": "风险可控性 - 失败风险和负面后果是否可控（1=风险极高难控，10=风险极低易控）",
    "tech": "技术可行性 - 技术上是否可以实现（1=完全不可行，10=技术成熟易实现）",
    "exec": "执行可行性 - 组织执行层面是否容易落地（1=几乎无法执行，10=非常容易执行）",
    "long_term": "长期价值 - 该方案是否具备长期战略价值（1=毫无长期价值，10=长期价值巨大）",
}

# ============================================================================
# 决策模式对应的上下文说明
# ============================================================================

DECISION_MODE_CONTEXT = {
    "multi_angle": """
你正在参与一个【多角度分析】决策会议。你的任务是：
- 从你的专业角度独立分析问题，给出完整的评估
- 不需要与其他观点辩论，只需充分表达你的专业判断
- 你的分析应完整、深入、有理有据""",

    "debate": """
你正在参与一场【正反辩论】。你的任务是：
- 根据你的立场，坚定地为支持或反对该方案提供论据
- 明确指出你对立方观点中可能存在的问题
- 论据要有理有据，但要保持专业风范""",

    "expert_consult": """
你正在参与一次【专家会诊】。你的任务是：
- 以你所在领域的专家身份，对该问题给出专业诊断
- 重点分析该方案在你专业领域内的影响和可行性
- 给出具体、可操作的专业建议""",

    "risk_review": """
你正在参与一次【风险评审】会议。你的任务是：
- 重点关注该方案可能存在的风险和失败场景
- 评估各类风险的发生概率和影响程度
- 为每项风险提供应对措施和兜底方案""",
}

# ============================================================================
# 统一的输出格式要求
# ============================================================================

OUTPUT_FORMAT_INSTRUCTION = """
【重要：你必须严格按照以下格式输出回复，不得遗漏任何部分】

---

## 观点摘要
（用 2~3 句话概括你的核心观点）

## 核心理由
（列出 3~5 条支持你观点的核心理由，每条理由前标序号）

## 收益分析
（分析该方案的潜在收益和正面影响）

## 成本分析
（分析该方案在资金、时间、人力等方面的成本投入）

## 风险分析
（分析该方案可能存在的风险和负面影响）

## 执行建议
（给出具体的执行步骤建议，分阶段说明）

## 适用条件
（说明你的建议在什么条件下最适用，什么情况下需要调整）

## 最终建议
（用 1~2 句话给出你最核心的建议）

## 维度评分
请严格以如下 JSON 格式给出 1~10 分的评分（注意：分数越高越好，使用"成本可控性"和"风险可控性"，不要使用"成本压力"或"风险等级"）：

```json
{
  "benefit": <1-10>,
  "cost": <1-10>,
  "risk": <1-10>,
  "tech": <1-10>,
  "exec": <1-10>,
  "long_term": <1-10>
}
```"""

# ============================================================================
# Prompt 构建入口函数
# ============================================================================


def build_agent_prompt(
    agent_name: str,
    role_description: str | None,
    focus_area: str | None,
    tone: str | None,
    decision_mode: str,
    question: str,
) -> str:
    """
    根据 Agent 配置和决策问题动态构建 System Prompt。

    参数:
        agent_name: Agent 展示名称（如 "创新增长派"）
        role_description: 角色/专业背景（如 "产品经理"）
        focus_area: 关注的分析领域（如 "增长机会、长期价值"）
        tone: 输出风格（如 "鼓励型"）
        decision_mode: 决策模式（multi_angle / debate / expert_consult / risk_review）
        question: 用户提出的决策问题

    返回:
        str: 完整的 System Prompt 字符串
    """
    # ---- 第 1 部分：Agent 人设定义 ----
    persona_parts = [f"你是「{agent_name}」，一位资深的决策分析专家。"]

    if role_description:
        persona_parts.append(f"你的专业背景是：{role_description}。")

    if focus_area:
        persona_parts.append(f"你特别关注以下领域：{focus_area}。")

    if tone:
        tone_map = {
            "鼓励型": "你的输出风格偏向积极鼓励，善于发现机遇和正面价值。",
            "严谨型": "你的输出风格偏向严谨审慎，注重数据和事实。",
            "中立型": "你的输出风格偏向客观中立，力求平衡各方观点。",
            "激进型": "你的输出风格偏向大胆进取，倾向于提出突破性建议。",
            "保守型": "你的输出风格偏向保守稳健，优先考虑风险最小化。",
        }
        persona_parts.append(tone_map.get(tone, f"你的输出风格偏向{tone}。"))

    persona_text = " ".join(persona_parts)

    # ---- 第 2 部分：决策模式上下文 ----
    mode_context = DECISION_MODE_CONTEXT.get(
        decision_mode,
        DECISION_MODE_CONTEXT["multi_angle"],
    )

    # ---- 第 3 部分：用户问题 ----
    question_text = f"【用户提出的决策问题】\n{question}"

    # ---- 第 4 部分：评分维度说明 ----
    dimensions_text = "【评分维度说明】\n你需要从以下六个维度对该方案进行评分（1~10 分）："
    for key, desc in SCORING_DIMENSIONS.items():
        dimensions_text += f"\n- {desc}"

    # ---- 拼接完整 System Prompt ----
    full_prompt = "\n\n".join([
        persona_text,
        mode_context,
        question_text,
        dimensions_text,
        OUTPUT_FORMAT_INSTRUCTION,
    ])

    return full_prompt


def build_default_weight_config() -> str:
    """
    返回默认的用户权重配置（JSON 字符串）。

    当用户未自定义权重时使用此默认值，
    各维度权重总和为 1.0（100%）。
    """
    import json

    default_weights = {
        "benefit": 0.20,    # 收益潜力
        "cost": 0.20,       # 成本可控性
        "risk": 0.20,       # 风险可控性
        "tech": 0.15,       # 技术可行性
        "exec": 0.15,       # 执行可行性
        "long_term": 0.10,  # 长期价值
    }
    return json.dumps(default_weights, ensure_ascii=False)
